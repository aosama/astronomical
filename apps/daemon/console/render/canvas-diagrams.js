/*
 * Diagrams (mermaid).
 *
 * A fenced ```mermaid block becomes a figure once its message has finished
 * streaming. The SVG mermaid produces is a whole document — its theme CSS, its
 * shapes, its text — so it is sanitised with an SVG-profile pass that is wider
 * than the markdown allowlist but still forbids anything that executes or embeds
 * markup. A diagram that cannot render keeps its source visible rather than
 * disappearing.
 */
(function () {
  "use strict";

  /**
   * Mermaid emits its theme as a `<style>` block inside the SVG; without it the
   * node labels lose their colour and vanish against the node fills. That CSS is
   * generated by mermaid from the theme rather than from diagram text (which the
   * sanitiser has already reduced to text nodes), and its selectors are scoped to
   * this figure's id, so the worst a hostile diagram can do is restyle its own
   * figure. Scripts, foreign objects, and event handlers stay forbidden, and CSP
   * keeps any network side channel closed.
   */
  var DIAGRAM_SVG_OPTIONS = {
    USE_PROFILES: { svg: true, svgFilters: true },
    ADD_TAGS: ["style"],
    FORBID_TAGS: ["foreignObject", "script", "iframe", "use"],
    FORBID_ATTR: ["onerror", "onload", "onclick"]
  };

  function initializeMermaid() {
    if (!window.mermaid || window.__thintalkMermaidReady) {
      return;
    }
    window.mermaid.initialize({
      startOnLoad: false,
      securityLevel: "strict",
      theme: "dark",
      // Mermaid labels flowcharts as HTML inside <foreignObject> by default, which
      // the SVG sanitiser forbids outright because it can carry arbitrary markup.
      // BOTH keys are required: measured in this shell, the flowchart key alone
      // still produced foreignObject, while both together produced native SVG
      // <text> labels that survive the strict list and stay readable.
      htmlLabels: false,
      flowchart: { htmlLabels: false },
      logLevel: 0
    });
    window.__thintalkMermaidReady = true;
  }

  function sanitizeDiagramSvg(svgText) {
    return DOMPurify.sanitize(svgText, DIAGRAM_SVG_OPTIONS);
  }

  /** Replaces the fenced source with the rendered figure, keeping the block key. */
  function installFigure(codeBlockWrapper, sanitisedSvg) {
    var figure = document.createElement("figure");
    figure.className = "diagram";
    figure.innerHTML = sanitisedSvg;
    codeBlockWrapper.innerHTML = "";
    codeBlockWrapper.appendChild(figure);
    codeBlockWrapper.classList.add("code-block--diagram");
  }

  /**
   * Renders every diagram in one finished message. Finished SVGs are cached by
   * content key so a later re-render of the same message re-installs them
   * synchronously instead of parsing mermaid again.
   */
  function render(root) {
    if (!window.mermaid) {
      return;
    }
    initializeMermaid();
    window.__thintalkDiagramCache = window.__thintalkDiagramCache || {};
    var diagramBlocks = root.querySelectorAll("pre > code.language-mermaid");
    Array.prototype.forEach.call(diagramBlocks, function (diagramBlock) {
      var pre = diagramBlock.parentElement;
      var codeBlockWrapper = pre && pre.parentElement;
      if (!codeBlockWrapper || !codeBlockWrapper.classList.contains("code-block")) {
        return;
      }
      var renderState = diagramBlock.dataset.diagram;
      if (renderState === "true" || renderState === "failed" || renderState === "pending") {
        return;
      }
      var diagramSource = diagramBlock.textContent || "";
      var cacheKey = "diagram-" + window.__thintalkContentKey.hash(diagramSource);
      var cachedSvg = window.__thintalkDiagramCache[cacheKey];
      if (cachedSvg) {
        installFigure(codeBlockWrapper, cachedSvg);
        diagramBlock.dataset.diagram = "true";
        return;
      }
      diagramBlock.dataset.diagram = "pending";
      window.mermaid
        .render(cacheKey, diagramSource)
        .then(function (renderResult) {
          if (!renderResult || !renderResult.svg) {
            throw new Error("mermaid produced no svg");
          }
          var sanitisedSvg = sanitizeDiagramSvg(renderResult.svg);
          if (sanitisedSvg.indexOf("<svg") === -1) {
            throw new Error("diagram svg did not survive sanitisation");
          }
          window.__thintalkDiagramCache[cacheKey] = sanitisedSvg;
          if (codeBlockWrapper.isConnected) {
            installFigure(codeBlockWrapper, sanitisedSvg);
          }
        })
        .catch(function () {
          // A diagram that cannot render keeps its source readable, the same way a
          // markdown fragment that cannot finish mid-stream stays visible.
          diagramBlock.dataset.diagram = "failed";
          if (codeBlockWrapper.isConnected) {
            codeBlockWrapper.classList.add("code-block--diagram-failed");
          }
        });
    });
  }

  window.__thintalkDiagrams = { render: render };
})();