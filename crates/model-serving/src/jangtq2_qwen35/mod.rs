//! The JANGTQ v2 (jangtq2) Qwen3.5 weight family.
//!
//! Discovery model type stays `qwen3_5_moe`: a jangtq2 bundle is a standard
//! Qwen3.5 hybrid MoE artifact whose routed-expert projections are stored in
//! the JANG codebook format instead of MLX affine quantization. The bundle is
//! recognized by the `jang_config.json` marker file, not by a new model type.
//!
//! This family owns the jangtq2 weight contract end to end — entry parsing,
//! the codebook math, the blockwise Hadamard rotation, the on-disk tensor
//! inventory, and (in the serving integration) the per-expert decode. The
//! standard `qwen3_5` family delegates here through a single opaque
//! foreign-format arm at the quantization-override seam and never defines
//! jangtq2 semantics itself. The same separation keeps future third-party
//! weight formats additive: one folder each, no per-format branches spread
//! through the serving path.
//!
//! # Format facts (source of truth: `jjang-ai/jangq`, `jang-tools/jang_tools/jangh/format.py`)
//!
//! * The `tq2_packed` bitstream is byte-identical to MLX affine packing for
//!   the supported widths (LSB-first continuous bitstream, every 32 codes
//!   occupying exactly `bits` `uint32` words).
//! * Codebook levels are evaluated arithmetically, never tabled:
//!   `level(q) = u · (alpha + beta · u²)` with `u = q - (2^bits - 1) / 2`.
//!   2-bit is exactly Lloyd-Max for N(0,1); 3-bit is +0.2% MSE, 4-bit +2%.
//! * `tq2_scales` carries one `float16` scale per expert row — the encoder's
//!   own solved scale, not a group scale.
//! * The `hadamard32` rotation is applied to activations at decode
//!   (`y = W_stored · h32(x)`) because the blockwise 32-wide Walsh-Hadamard
//!   is self-inverse and orthonormal; weights are never un-rotated.
//! * Routed experts are stacked per layer: one `tq2_packed` /
//!   `tq2_scales` tensor pair per projection covers all experts of the layer
//!   with shape `(experts, outputs, inputs · bits / 32)`.
//!
//! Golden vectors pinning this implementation to the reference live in
//! `tests/golden_reference_vectors.json` and were generated by running the
//! reference `format.py` directly.

