//! Explicit inputs published by `cargo xtask test-run` in its owned run directory.

use std::collections::BTreeMap;
use std::fs::{self, OpenOptions};
use std::io::{self, Write};
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

pub const TEST_RUN_CONTEXT_FILE_NAME: &str = "astronomical-test-run.json";
const BYTES_PER_GIGABYTE: u64 = 1 << 30;

#[derive(Clone, Debug, Deserialize, PartialEq, Eq, Serialize)]
#[serde(default, deny_unknown_fields)]
pub struct PagingExperimentCase {
    pub maximum_mlx_memory_gigabytes: u64,
    pub streaming_prompt_processing_chunk_tokens: u32,
    pub prefill_graph_submission_layer_interval: u32,
    pub generation_graph_submission_layer_interval: u32,
}

impl Default for PagingExperimentCase {
    fn default() -> Self {
        Self {
            maximum_mlx_memory_gigabytes: 32,
            streaming_prompt_processing_chunk_tokens: 2_048,
            prefill_graph_submission_layer_interval: 1,
            generation_graph_submission_layer_interval: 1,
        }
    }
}

impl PagingExperimentCase {
    pub fn maximum_mlx_memory_bytes(&self) -> Result<u64, String> {
        if self.maximum_mlx_memory_gigabytes == 0 {
            return Err("paging experiment memory must be at least one gigabyte".to_owned());
        }
        self.maximum_mlx_memory_gigabytes
            .checked_mul(BYTES_PER_GIGABYTE)
            .ok_or_else(|| "paging experiment memory exceeds the byte-count range".to_owned())
    }

    fn validate(&self) -> Result<(), String> {
        self.maximum_mlx_memory_bytes()?;
        if self.streaming_prompt_processing_chunk_tokens == 0
            || self.prefill_graph_submission_layer_interval == 0
            || self.generation_graph_submission_layer_interval == 0
        {
            return Err(
                "paging experiment token counts and layer intervals must be positive".to_owned(),
            );
        }
        Ok(())
    }
}

/// Only supported test inputs live here; build provenance is generated by the runner.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(default, deny_unknown_fields)]
pub struct TestRunConfiguration {
    pub model_directory: Option<PathBuf>,
    pub evidence_directory: Option<PathBuf>,
    pub real_models: bool,
    pub diagnostics: bool,
    pub retain_isolated_home: bool,
    pub allow_large_wired_memory_probe: bool,
    pub paging_experiment: PagingExperimentCase,
    pub prefix_adoption_enabled: Option<bool>,
    pub prompt_processing_chunk_tokens: Option<u32>,
    pub sweep_cell_order: u32,
    pub throughput_history_path: Option<PathBuf>,
    pub coverage_inventory_output: Option<PathBuf>,
}

impl TestRunConfiguration {
    pub fn validate(&self) -> Result<(), String> {
        self.paging_experiment.validate()?;
        if self.prompt_processing_chunk_tokens == Some(0) {
            return Err("prompt-processing chunk token count must be positive".to_owned());
        }
        for (path_description, configured_path) in self.configured_paths() {
            if configured_path.is_some_and(|path| path.as_os_str().is_empty()) {
                return Err(format!("{path_description} must not be empty"));
            }
        }
        Ok(())
    }

    pub fn resolve_paths(&mut self, configuration_directory: &Path) {
        for configured_path in [
            &mut self.model_directory,
            &mut self.evidence_directory,
            &mut self.throughput_history_path,
            &mut self.coverage_inventory_output,
        ] {
            if let Some(relative_path) = configured_path.as_ref().filter(|path| path.is_relative())
            {
                *configured_path = Some(configuration_directory.join(relative_path));
            }
        }
    }

    fn configured_paths(&self) -> [(&'static str, Option<&Path>); 4] {
        [
            ("model directory", self.model_directory.as_deref()),
            ("evidence directory", self.evidence_directory.as_deref()),
            (
                "throughput history path",
                self.throughput_history_path.as_deref(),
            ),
            (
                "coverage inventory output",
                self.coverage_inventory_output.as_deref(),
            ),
        ]
    }
}

/// A run-scoped manifest binds test inputs to the exact executables Cargo built.
///
/// Libtest owns test-process arguments. An owned working directory lets the
/// runner publish typed inputs without global files, process-environment
/// mutation, or repurposing libtest flags as a hidden transport.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(default, deny_unknown_fields)]
pub struct TestRunContext {
    pub configuration: TestRunConfiguration,
    pub workspace_binaries: BTreeMap<String, PathBuf>,
    pub workspace_binary_sha256: BTreeMap<String, String>,
    pub source_commit: Option<String>,
    pub source_is_dirty: bool,
}

impl TestRunContext {
    pub fn current() -> Self {
        let working_directory =
            std::env::current_dir().expect("the test working directory should resolve");
        Self::read_from_directory(&working_directory)
            .unwrap_or_else(|read_error| {
                panic!("the explicit test-run context should load: {read_error}")
            })
            .unwrap_or_default()
    }

    pub fn read_from_directory(run_directory: &Path) -> io::Result<Option<Self>> {
        let manifest_path = run_directory.join(TEST_RUN_CONTEXT_FILE_NAME);
        let manifest_bytes = match fs::read(&manifest_path) {
            Ok(manifest_bytes) => manifest_bytes,
            Err(read_error) if read_error.kind() == io::ErrorKind::NotFound => return Ok(None),
            Err(read_error) => return Err(read_error),
        };
        let run_context: Self =
            serde_json::from_slice(&manifest_bytes).map_err(io::Error::other)?;
        run_context.validate().map_err(|validation_error| {
            io::Error::new(io::ErrorKind::InvalidData, validation_error)
        })?;
        Ok(Some(run_context))
    }

    pub fn write_to_directory(&self, run_directory: &Path) -> io::Result<()> {
        self.validate().map_err(|validation_error| {
            io::Error::new(io::ErrorKind::InvalidInput, validation_error)
        })?;
        let manifest_bytes = serde_json::to_vec_pretty(self).map_err(io::Error::other)?;
        let mut manifest_file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(run_directory.join(TEST_RUN_CONTEXT_FILE_NAME))?;
        manifest_file.write_all(&manifest_bytes)
    }

    pub fn required_model_directory(&self) -> PathBuf {
        let model_directory =
            self.configuration.model_directory.as_ref().expect(
                "select a model_directory in the configuration passed to cargo xtask test-run",
            );
        assert!(
            model_directory.is_dir(),
            "the selected model directory does not exist: {}",
            model_directory.display()
        );
        model_directory.clone()
    }

    fn validate(&self) -> Result<(), String> {
        self.configuration.validate()?;
        for (path_description, configured_path) in self.configuration.configured_paths() {
            if configured_path.is_some_and(|path| path.is_relative()) {
                return Err(format!(
                    "{path_description} must be resolved before test launch"
                ));
            }
        }
        for (binary_name, executable_path) in &self.workspace_binaries {
            if binary_name.is_empty() || !executable_path.is_absolute() {
                return Err(
                    "workspace binaries need nonempty names and absolute executable paths"
                        .to_owned(),
                );
            }
        }
        for (binary_name, executable_sha256) in &self.workspace_binary_sha256 {
            if !self.workspace_binaries.contains_key(binary_name)
                || executable_sha256.len() != 64
                || !executable_sha256
                    .bytes()
                    .all(|character| character.is_ascii_hexdigit())
            {
                return Err(
                    "workspace binary digests must identify a selected executable with SHA-256"
                        .to_owned(),
                );
            }
        }
        Ok(())
    }
}

