//! Typed port of `scripts/check-source-size.sh`: enforces the repository's
//! file-length budgets for workspace sources, with the same progress and
//! ETA reporting the shell tool emitted.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Instant;

const MAXIMUM_SOURCE_LINES: usize = 650;
const WARNING_SOURCE_LINES: usize = 600;
const MAXIMUM_STAGED_SOURCE_LINES: usize = 700;
const MAXIMUM_ELAPSED_SECONDS: u64 = 120;
const PROGRESS_INTERVAL_FILES: usize = 100;

const SOURCE_FILE_EXTENSIONS: [&str; 19] = [
    "rs", "py", "sh", "swift", "c", "cc", "cpp", "cxx", "h", "hh", "hpp", "hxx", "m", "mm",
    "metal", "js", "jsx", "ts", "tsx",
];

struct Progress {
    started_at: Instant,
    total_files: usize,
    checked_files: usize,
}

impl Progress {
    fn report(&mut self, checked_files: usize) {
        self.checked_files = checked_files;
        let elapsed_seconds = self.started_at.elapsed().as_secs();
        let (percentage, eta_seconds) = if self.total_files == 0 {
            (100, 0u64)
        } else if checked_files == 0 || elapsed_seconds == 0 {
            (checked_files * 100 / self.total_files, 0)
        } else {
            let estimated_total_seconds =
                (elapsed_seconds * self.total_files as u64 + checked_files as u64 - 1)
                    / checked_files as u64;
            (
                checked_files * 100 / self.total_files,
                estimated_total_seconds - elapsed_seconds,
            )
        };
        println!(
            "[source-size] status=progress files={checked_files}/{} percentage={percentage} ETA_seconds={eta_seconds} elapsed_seconds={elapsed_seconds}",
            self.total_files
        );
    }

    fn should_report(&self, checked_files: usize) -> bool {
        checked_files % PROGRESS_INTERVAL_FILES == 0 || checked_files == self.total_files
    }

    fn assert_within_timeout(&self) -> Result<(), String> {
        if self.started_at.elapsed().as_secs() > MAXIMUM_ELAPSED_SECONDS {
            Err(format!(
                "[source-size] status=failed reason=timeout limit_seconds={MAXIMUM_ELAPSED_SECONDS}"
            ))
        } else {
            Ok(())
        }
    }
}

/// A source file whose first line marks it as deterministically generated is
/// exempt: nobody authors those lines here.
fn is_deterministically_generated_binding(source_text: &str) -> bool {
    let Some(first_line) = source_text.lines().next() else {
        return false;
    };
    ["// @generated", "/* @generated", "# @generated"]
        .into_iter()
        .chain([
            "// automatically generated by rust-bindgen",
            "/* automatically generated by rust-bindgen",
            "# automatically generated by rust-bindgen",
        ])
        .any(|marker| first_line.starts_with(marker))
}

/// `sed -n '$='` semantics: newline count, plus one when the file ends
/// without a trailing newline on a nonempty final line.
fn count_source_lines(source_text: &str) -> usize {
    let newline_count = source_text.matches('\n').count();
    if source_text.is_empty() {
        0
    } else if source_text.ends_with('\n') {
        newline_count
    } else {
        newline_count + 1
    }
}

fn is_vendored_asset_path(relative_path: &str) -> bool {
    relative_path.contains("/vendor/") || relative_path.starts_with("vendor/")
}

fn collect_workspace_rs_files(root: &Path) -> Vec<PathBuf> {
    let mut collected = Vec::new();
    collect_workspace_rs_files_inner(root, &mut collected);
    collected
}

fn collect_workspace_rs_files_inner(directory: &Path, collected: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(directory) else {
        return;
    };
    for entry in entries.flatten() {
        let entry_path = entry.path();
        let file_name = entry.file_name();
        let file_name = file_name.to_string_lossy();
        if entry_path.is_dir() {
            // Mirrors find's `! -path '*/target/*' ! -path '*/tests/*'`.
            if file_name == "target" || file_name == "tests" {
                continue;
            }
            collect_workspace_rs_files_inner(&entry_path, collected);
        } else if file_name.ends_with(".rs") {
            collected.push(entry_path);
        }
    }
}

fn run_workspace_mode(repository_root: &Path) -> Result<(), String> {
    println!(
        "[source-size] status=start timeout_seconds={MAXIMUM_ELAPSED_SECONDS} root={}",
        repository_root.display()
    );
    let source_files = collect_workspace_rs_files(repository_root);
    let mut progress = Progress {
        started_at: Instant::now(),
        total_files: source_files.len(),
        checked_files: 0,
    };
    let mut warning_count = 0usize;
    let mut failing_count = 0usize;

    for (checked_index, source_file) in source_files.iter().enumerate() {
        progress.assert_within_timeout()?;
        let checked_count = checked_index + 1;
        let Ok(source_text) = fs::read_to_string(source_file) else {
            continue;
        };
        if !is_deterministically_generated_binding(&source_text) {
            let line_count = count_source_lines(&source_text);
            if line_count > MAXIMUM_SOURCE_LINES {
                failing_count += 1;
                println!(
                    "[source-size] status=failed lines={line_count} limit={MAXIMUM_SOURCE_LINES} path={}",
                    source_file.display()
                );
            } else if line_count > WARNING_SOURCE_LINES {
                warning_count += 1;
                println!(
                    "[source-size] status=warning lines={line_count} threshold={} path={}",
                    WARNING_SOURCE_LINES + 1,
                    source_file.display()
                );
            }
        }
        if progress.should_report(checked_count) {
            progress.report(checked_count);
        }
    }
    if source_files.is_empty() {
        progress.report(0);
    }

    if failing_count > 0 {
        println!(
            "[source-size] status=failed files={failing_count} warnings={warning_count} elapsed_seconds={}",
            progress.started_at.elapsed().as_secs()
        );
        return Err(String::new());
    }
    println!(
        "[source-size] status=success files={} warnings={warning_count} elapsed_seconds={}",
        progress.checked_files,
        progress.started_at.elapsed().as_secs()
    );
    Ok(())
}

fn is_staged_source_file_path(path_text: &str) -> bool {
    path_text
        .rsplit('.')
        .next()
        .is_some_and(|extension| SOURCE_FILE_EXTENSIONS.contains(&extension))
}

fn run_staged_mode() -> Result<(), String> {
    // Git calls intentionally run against the invoking process's repository —
    // the pre-commit hook may fire inside another checkout (worktrees, test
    // sandboxes), and the staged index that matters is the caller's.
    let staged_paths = Command::new("git")
        .args(["diff", "--cached", "--name-only", "--diff-filter=ACMR"])
        .output()
        .map_err(|error| {
            format!("[source-size] status=failed reason=git-unavailable error={error}")
        })?;
    if !staged_paths.status.success() {
        return Err("[source-size] status=failed reason=git-diff-failed".to_owned());
    }
    let staged_path_list: Vec<String> = String::from_utf8_lossy(&staged_paths.stdout)
        .lines()
        .map(str::to_owned)
        .collect();
    let mut progress = Progress {
        started_at: Instant::now(),
        total_files: staged_path_list.len(),
        checked_files: 0,
    };
    println!(
        "[source-size] status=start mode=staged timeout_seconds={MAXIMUM_ELAPSED_SECONDS} root={}",
        std::env::current_dir()
            .map(|directory| directory.to_string_lossy().into_owned())
            .unwrap_or_else(|_| "unknown".to_owned())
    );
    let mut failing_count = 0usize;

    for staged_path in &staged_path_list {
        progress.assert_within_timeout()?;
        if !is_staged_source_file_path(staged_path) || is_vendored_asset_path(staged_path) {
            continue;
        }
        let checked_count = progress.checked_files + 1;
        progress.checked_files = checked_count;
        let staged_blob = Command::new("git")
            .args(["show", &format!(":{staged_path}")])
            .output();
        let Ok(staged_blob) = staged_blob else {
            failing_count += 1;
            eprintln!(
                "[source-size] status=failed reason=unreadable-staged-source path={staged_path}"
            );
            continue;
        };
        if !staged_blob.status.success() {
            failing_count += 1;
            eprintln!(
                "[source-size] status=failed reason=unreadable-staged-source path={staged_path}"
            );
            continue;
        }
        let source_text = String::from_utf8_lossy(&staged_blob.stdout).into_owned();
        if !is_deterministically_generated_binding(&source_text) {
            let line_count = count_source_lines(&source_text);
            if line_count > MAXIMUM_STAGED_SOURCE_LINES {
                failing_count += 1;
                println!(
                    "[source-size] status=failed lines={line_count} limit={MAXIMUM_STAGED_SOURCE_LINES} path={staged_path}"
                );
            }
        }
        if progress.should_report(checked_count) {
            progress.report(checked_count);
        }
    }
    if progress.checked_files == 0 {
        progress.report(0);
    }

    if failing_count > 0 {
        println!(
            "[source-size] status=failed mode=staged files={failing_count} elapsed_seconds={}",
            progress.started_at.elapsed().as_secs()
        );
        return Err(String::new());
    }
    println!(
        "[source-size] status=success mode=staged files={} elapsed_seconds={}",
        progress.checked_files,
        progress.started_at.elapsed().as_secs()
    );
    Ok(())
}

pub fn run(repository_root: &Path, arguments: &[String]) -> Result<(), String> {
    match arguments.first().map(String::as_str) {
        None => run_workspace_mode(repository_root),
        Some("--staged") if arguments.len() == 1 => run_staged_mode(),
        Some(path_or_flag) if !path_or_flag.starts_with('-') && arguments.len() == 1 => {
            run_workspace_mode(Path::new(path_or_flag))
        }
        _ => Err("[source-size] status=failed reason=unexpected-arguments".to_owned()),
    }
}
