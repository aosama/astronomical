//! The source-size rules and the workspace scan, ported from the scenarios of
//! the former `verification/tooling_contracts/test-source-size-check.sh`
//! (issue #2635).

use std::fs;
use std::path::Path;

use super::source_size::{
    count_source_lines, is_deterministically_generated_binding, is_staged_source_file_path,
    is_vendored_asset_path, run,
};

const SOURCE_LINE: &str = "// structural source-size test line\n";

/// A Rust file of `line_count` lines under `root/src`, the first replaced by
/// `first_line` when one is given.
fn write_rust_source(root: &Path, file_name: &str, line_count: usize, first_line: Option<&str>) {
    let source_text = match first_line {
        Some(header_line) => format!("{header_line}\n{}", SOURCE_LINE.repeat(line_count - 1)),
        None => SOURCE_LINE.repeat(line_count),
    };
    fs::create_dir_all(root.join("src")).expect("the source folder should be creatable");
    fs::write(root.join("src").join(file_name), source_text)
        .expect("the source file should be writable");
}

fn scan_workspace(root: &Path) -> Result<(), String> {
    run(root, &[root.to_string_lossy().into_owned()])
}

#[test]
fn should_count_a_missing_final_newline_as_a_line() {
    assert_eq!(count_source_lines(""), 0);
    assert_eq!(count_source_lines("one\ntwo\n"), 2);
    assert_eq!(count_source_lines("one\ntwo"), 2);
    assert_eq!(count_source_lines("\n"), 1);
}

#[test]
fn should_exempt_only_a_file_whose_first_line_says_it_is_generated() {
    assert!(is_deterministically_generated_binding(
        "// @generated deterministic binding\nfn a() {}\n"
    ));
    assert!(is_deterministically_generated_binding(
        "# @generated\nx = 1\n"
    ));
    assert!(is_deterministically_generated_binding(
        "/* automatically generated by rust-bindgen 0.70 */\n"
    ));
    assert!(!is_deterministically_generated_binding(
        "// This hand-written source mentions @generated but is not generated.\n"
    ));
    assert!(!is_deterministically_generated_binding(
        "fn a() {}\n// @generated\n"
    ));
    assert!(!is_deterministically_generated_binding(""));
}

#[test]
fn should_check_staged_code_of_every_language_but_not_documentation() {
    for source_path in [
        "a.rs", "b.py", "C.swift", "d.cpp", "e.metal", "f.tsx", "g.sh",
    ] {
        assert!(is_staged_source_file_path(source_path), "{source_path}");
    }
    for other_path in ["oversized.md", "data.json", "Makefile", "rs"] {
        assert!(!is_staged_source_file_path(other_path), "{other_path}");
    }
}

#[test]
fn should_exempt_vendored_assets() {
    assert!(is_vendored_asset_path(
        "Sources/App/Resources/web/vendor/bundle.min.js"
    ));
    assert!(is_vendored_asset_path("vendor/bundle.min.js"));
    assert!(!is_vendored_asset_path("src/vendors.rs"));
}

#[test]
fn should_pass_a_workspace_file_at_the_warning_threshold() {
    let sandbox = tempfile::tempdir().expect("a sandbox should be creatable");
    write_rust_source(sandbox.path(), "warning.rs", 601, None);
    assert_eq!(scan_workspace(sandbox.path()), Ok(()));
}

#[test]
fn should_pass_a_workspace_file_at_the_limit() {
    let sandbox = tempfile::tempdir().expect("a sandbox should be creatable");
    write_rust_source(sandbox.path(), "boundary.rs", 700, None);
    assert_eq!(scan_workspace(sandbox.path()), Ok(()));
}

#[test]
fn should_fail_a_workspace_file_over_the_limit() {
    let sandbox = tempfile::tempdir().expect("a sandbox should be creatable");
    write_rust_source(sandbox.path(), "failing.rs", 701, None);
    assert!(scan_workspace(sandbox.path()).is_err());
}

#[test]
fn should_fail_an_oversized_file_without_a_final_newline() {
    let sandbox = tempfile::tempdir().expect("a sandbox should be creatable");
    fs::create_dir_all(sandbox.path().join("src")).expect("the source folder should be creatable");
    let source_without_final_newline = format!("{}last line", SOURCE_LINE.repeat(700));
    fs::write(
        sandbox.path().join("src/no_final_newline.rs"),
        source_without_final_newline,
    )
    .expect("the source file should be writable");
    assert!(scan_workspace(sandbox.path()).is_err());
}

#[test]
fn should_skip_a_generated_workspace_file_but_not_one_that_only_mentions_the_marker() {
    let generated_sandbox = tempfile::tempdir().expect("a sandbox should be creatable");
    write_rust_source(
        generated_sandbox.path(),
        "generated.rs",
        900,
        Some("// @generated deterministic binding"),
    );
    assert_eq!(scan_workspace(generated_sandbox.path()), Ok(()));

    let misleading_sandbox = tempfile::tempdir().expect("a sandbox should be creatable");
    write_rust_source(
        misleading_sandbox.path(),
        "hand_written.rs",
        701,
        Some("// This hand-written source mentions @generated but is not generated."),
    );
    assert!(scan_workspace(misleading_sandbox.path()).is_err());
}

#[test]
fn should_refuse_unexpected_arguments() {
    let sandbox = tempfile::tempdir().expect("a sandbox should be creatable");
    let unexpected_arguments = ["--staged".to_owned(), "extra".to_owned()];
    assert!(run(sandbox.path(), &unexpected_arguments).is_err());
    assert!(run(sandbox.path(), &["--verbose".to_owned()]).is_err());
}
